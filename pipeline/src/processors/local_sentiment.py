# 부정 의미를 뒤집는 패턴 (긍정 단어 앞 부정어) — "안 좋", "재미 없" 등
_NEG_FLIP = re.compile(r"(안|못|안나|노)\s*(좋|재밌|재미|행복|만족)")


def _score(text: str, lexicon: dict[str, int]) -> int:
    return sum(weight for kw, weight in lexicon.items() if kw in text)


def classify_local(post: dict) -> dict:
    """게시글 하나를 로컬 키워드 점수로 분류.

    Returns:
        {"sentiment", "categories", "issue_summary", "keywords", "model"}
        — Gemini classify_post과 동일한 형식이라 update_classification에 그대로 사용 가능.
    """
    title = (post.get("title") or "").strip()
    body = (post.get("body") or "").strip()
    text = f"{title} {body}"

    neg = _score(text, _NEGATIVE)
    pos = _score(text, _POSITIVE)

    # "안 좋다" 같은 부정 표현 보정: 긍정 점수를 부정으로 이동
    if _NEG_FLIP.search(text):
        neg += 2
        pos = max(0, pos - 2)

    if neg > pos:
        sentiment = "negative"
    elif pos > neg:
        sentiment = "positive"
    else:
        sentiment = "neutral"

    return {
        "sentiment": sentiment,
        "categories": _categorize(text),
        "issue_summary": title or None,  # 로컬 모드에선 제목을 이슈 요약으로 사용
        "keywords": _extract_keywords(text),
        "model": "local-keyword",
    }


