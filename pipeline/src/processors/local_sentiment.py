_CLASS_NAMES = ("검성", "수호성", "살성", "궁성", "호법성", "치유성", "마도성", "정령성")


def _categorize(text: str) -> list[str]:
    cats = [cat for cat, kws in _CATEGORY_KEYWORDS.items() if any(k in text for k in kws)]
    return cats[:3] or ["기타"]


def _extract_keywords(text: str) -> list[str]:
    """제목에서 직업명·감성 키워드를 추출 (간이)."""
    found: list[str] = []
    for name in _CLASS_NAMES:
        if name in text and name not in found:
            found.append(name)
    for kw in list(_NEGATIVE) + list(_POSITIVE):
        if len(found) >= 5:
            break
        # ㅡㅡ 같은 이모티콘성 키워드는 제외
        if kw.isalpha() and kw in text and kw not in found:
            found.append(kw)
    return found[:5]
